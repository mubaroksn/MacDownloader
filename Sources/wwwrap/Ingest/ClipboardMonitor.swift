import AppKit
import DownloadCore
import Foundation
import UserNotifications

/// Decides whether a copied string is worth offering as a download.
enum DownloadableLink {
    static func detect(in text: String) -> URL? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.count < 4096, !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              let host = url.host?.lowercased(), !host.isEmpty else { return nil }

        if LinkResolver.directURL(for: url) != nil { return url }               // Drive, Dropbox, GitHub, …
        if DriveFolder.folderID(from: url) != nil { return url }               // whole Drive folders
        if host.hasSuffix("mediafire.com"), url.path.hasPrefix("/file") { return url }
        let ext = url.pathExtension.lowercased()
        if !ext.isEmpty, FileCategory.from(fileName: "x.\(ext)") != .other { return url }
        return nil
    }
}

/// IDM-style clipboard watching: copy a download link anywhere (any browser, chat, mail)
/// and wwwrap offers to download it. This works without any browser extension.
///
/// Cost: one `changeCount` read per second (a cheap integer IPC); the timer has 0.5 s
/// tolerance so it coalesces with other wakeups. Contents are only read after a change,
/// and password-manager entries (concealed/transient pasteboard types) are never read.
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var lastOffered: String?

    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    func setEnabled(_ enabled: Bool) {
        if enabled { start() } else { stop() }
    }

    private func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount // don't offer what was copied before enabling
        let timer = Timer(timeInterval: 1.0, repeats: true) { _ in
            Task { @MainActor in ClipboardMonitor.shared.check() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        guard !NSApp.isActive else { return } // our own "Salin link" or the user pasting into the Add sheet
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes),
              let text = pasteboard.string(forType: .string),
              let url = DownloadableLink.detect(in: text),
              url.absoluteString != lastOffered,
              !DownloadManager.shared.items.contains(where: { ($0.sourceURL ?? $0.url) == url }) else { return }

        lastOffered = url.absoluteString
        LinkOffer.present(url)
    }
}

/// Shows a copied link as a notification with a Download button, and as a banner in the app.
@MainActor
enum LinkOffer {
    static let category = "LINK_OFFER"
    static let downloadAction = "DOWNLOAD"
    static let ignoreAction = "IGNORE"

    static func registerCategories() {
        let download = UNNotificationAction(identifier: downloadAction, title: "Download", options: [])
        let ignore = UNNotificationAction(identifier: ignoreAction, title: L("Abaikan"), options: [])
        let offer = UNNotificationCategory(identifier: category, actions: [download, ignore],
                                           intentIdentifiers: [], options: [])
        UNUserNotificationCenter.current().setNotificationCategories([offer])
        UNUserNotificationCenter.current().delegate = NotificationRouter.shared
    }

    static func present(_ url: URL) {
        UIState.shared.clipboardOffer = url

        let content = UNMutableNotificationContent()
        content.title = L("Link download tersalin")
        content.body = displayName(for: url)
        content.categoryIdentifier = category
        content.userInfo = ["url": url.absoluteString]
        UNUserNotificationCenter.current().add(
            UNNotificationRequest(identifier: "offer-\(url.absoluteString.hashValue)", content: content, trigger: nil))
    }

    static func accept(_ url: URL) {
        DownloadManager.shared.add(urlString: url.absoluteString, origin: .clipboard)
        if UIState.shared.clipboardOffer == url { UIState.shared.clipboardOffer = nil }
    }

    static func dismiss() { UIState.shared.clipboardOffer = nil }

    static func displayName(for url: URL) -> String {
        if DriveFolder.folderID(from: url) != nil { return L("Folder Google Drive · semua isinya") }
        let name = url.lastPathComponent.removingPercentEncoding ?? url.lastPathComponent
        let host = url.host ?? ""
        return name.isEmpty || name == "/" || !name.contains(".") ? host + url.path : "\(name) · \(host)" // l10n-ignore
    }
}

final class NotificationRouter: NSObject, UNUserNotificationCenterDelegate {
    static let shared = NotificationRouter()

    func userNotificationCenter(_ center: UNUserNotificationCenter, willPresent notification: UNNotification,
                                withCompletionHandler completionHandler: @escaping (UNNotificationPresentationOptions) -> Void) {
        completionHandler([.banner, .sound])
    }

    func userNotificationCenter(_ center: UNUserNotificationCenter, didReceive response: UNNotificationResponse,
                                withCompletionHandler completionHandler: @escaping () -> Void) {
        let info = response.notification.request.content
        if info.categoryIdentifier == LinkOffer.category,
           let string = info.userInfo["url"] as? String, let url = URL(string: string) {
            let action = response.actionIdentifier
            Task { @MainActor in
                if action == LinkOffer.downloadAction || action == UNNotificationDefaultActionIdentifier {
                    LinkOffer.accept(url)
                } else {
                    LinkOffer.dismiss()
                }
            }
        }
        completionHandler()
    }
}
